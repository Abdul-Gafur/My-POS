    /**
     * 
     * @param type $value
     * @return boolean
     */
    public function itemsearch($value){
        $q = "SELECT * FROM items 
            WHERE 
            name LIKE '%".$this->db->escape_like_str($value)."%'
            || 
            code LIKE '%".$this->db->escape_like_str($value)."%'";
        
        $run_q = $this->db->query($q, [$value, $value]);
        
        if($run_q->num_rows() > 0){
            return $run_q->result();
        }
        
        else{
            return FALSE;
        }
    }
    
    /**
     * Enhanced search with filters
     * @param string $search_value
     * @param string $category
     * @param float $price_min
     * @param float $price_max
     * @param string $stock_status (all, in_stock, low_stock, out_of_stock)
     * @return boolean
     */
    public function enhancedSearch($search_value = '', $category = '', $price_min = '', $price_max = '', $stock_status = 'all'){
        $this->db->select('*');
        
        // Text search
        if (!empty($search_value)) {
            $this->db->group_start();
            $this->db->like('name', $search_value);
            $this->db->or_like('code', $search_value);
            $this->db->or_like('description', $search_value);
            $this->db->group_end();
        }
        
        // Category filter (if category column exists)
        if (!empty($category)) {
            $this->db->where('category', $category);
        }
        
        // Price range filter
        if (!empty($price_min)) {
            $this->db->where('unitPrice >=', floatval($price_min));
        }
        if (!empty($price_max)) {
            $this->db->where('unitPrice <=', floatval($price_max));
        }
        
        // Stock status filter
        switch ($stock_status) {
            case 'in_stock':
                $this->db->where('quantity >', 0);
                break;
            case 'low_stock':
                // Assuming low stock is less than 10
                $this->db->where('quantity >', 0);
                $this->db->where('quantity <', 10);
                break;
            case 'out_of_stock':
                $this->db->where('quantity', 0);
                break;
        }
        
        $this->db->order_by('name', 'ASC');
        $run_q = $this->db->get('items');
        
        if($run_q->num_rows() > 0){
            return $run_q->result();
        }
        
        return FALSE;
    }
    
    
